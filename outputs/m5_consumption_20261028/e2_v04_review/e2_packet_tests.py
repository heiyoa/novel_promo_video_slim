# -*- coding: utf-8 -*-
"""Integrity tests for the M5 v0.4 E2 evidence packet and review records.

Validates structure, counts, SHA bindings and cross-references of the evidence
generated by packet_generator.py plus the hand-authored review records.
Run:  python -m unittest e2_packet_tests -v   (from this directory)
"""
from __future__ import annotations

import hashlib
import json
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(name: str) -> dict:
    return json.loads((HERE / name).read_text(encoding="utf-8"))


class EvidencePacketTests(unittest.TestCase):
    def setUp(self):
        self.packet = load("evidence_packet.json")
        self.artifacts = self.packet["artifacts"]

    def test_both_artifacts_present(self):
        self.assertEqual(set(self.artifacts), {"love_hidden", "fitness_reset"})

    def test_video_sha256_bound(self):
        self.assertEqual(self.artifacts["love_hidden"]["probe"]["video_sha256"],
                         "9088b0e8ba92064bab50b895d3969c6a97a66cd142964c8aa7bfc23ef10aecdc")
        self.assertEqual(self.artifacts["fitness_reset"]["probe"]["video_sha256"],
                         "fd5a2466f292529fe08e85932a9b07208cc44d9dd815e43206dc5d57d04737f0")

    def test_github_main_blob_matches(self):
        for name, entry in self.artifacts["love_hidden"].items():
            if isinstance(entry, dict) and "matches_github_main_blob" in entry:
                self.assertTrue(entry["matches_github_main_blob"], name)

    def test_intent_gap_counts(self):
        lh = self.artifacts["love_hidden"]["evidence"]["intent_gap"]
        fi = self.artifacts["fitness_reset"]["evidence"]["intent_gap"]
        self.assertEqual((lh["script_slide_count"], lh["draft_video_material_count"]), (8, 1))
        self.assertEqual((fi["script_slide_count"], fi["draft_video_material_count"]), (6, 1))
        self.assertEqual(lh["planned_total_duration_s"], 45.0)
        self.assertEqual(fi["planned_total_duration_s"], 18.0)

    def test_static_video_evidence(self):
        for key, cue_count in (("love_hidden", 20), ("fitness_reset", 10)):
            ev = self.artifacts[key]["evidence"]
            self.assertEqual(ev["srt_stats"]["cue_count"], cue_count)
            self.assertEqual(ev["scene_changes_detected"], [],
                             "scene detection must confirm the static-photo draft")
            self.assertEqual(len(ev["storyboard"]), cue_count,
                             "one midpoint frame per cue")
            for frame in ev["storyboard"]:
                p = HERE / f"storyboard_{key}" / frame["file"]
                self.assertTrue(p.is_file(), frame["file"])
                self.assertEqual(hashlib.sha256(p.read_bytes()).hexdigest(), frame["sha256"])
            sheet = HERE / f"{'love_hidden' if key == 'love_hidden' else 'fitness_reset'}_contact_sheet.jpg"
            self.assertTrue(sheet.is_file())

    def test_audio_content_stays_unknown(self):
        for key in self.artifacts:
            facts = self.artifacts[key]["evidence"]["audio_tech_facts"]
            self.assertIn("UNKNOWN", facts["note"])


class RubricAndReviewTests(unittest.TestCase):
    def setUp(self):
        self.rubric = load("e2_rubric_frozen.json")
        self.reviews = [load("review_love_hidden.json"), load("review_fitness_reset.json")]
        self.attacks = load("rubric_contrast_attack.json")
        self.decisions = [load("consumer_decision_love_hidden.json"),
                          load("consumer_decision_fitness_reset.json")]
        self.packet = load("evidence_packet.json")

    def test_rubric_is_frozen_before_review_and_has_anti_gaming(self):
        self.assertTrue(self.rubric["frozen_at"] < self.reviews[0]["reviewed_at"])
        self.assertGreaterEqual(len(self.rubric["anti_gaming_rules"]), 4)
        self.assertIn("WAIT_MISSING_PACKAGE", self.rubric["canonical_package_status"])

    def test_reviews_never_pass_e2_and_keep_audio_unknown(self):
        for review in self.reviews:
            self.assertEqual(review["overall_e2"], "NOT_PASS")
            self.assertEqual(review["dimensions"]["d5_audio_content"]["verdict"], "UNKNOWN")
            self.assertIn("UNKNOWN", review["overall_note"])

    def test_reviews_reference_exact_media_sha(self):
        for review in self.reviews:
            key = "love_hidden" if "Love_Hidden" in review["reviewed_media"] else "fitness_reset"
            self.assertEqual(review["media_sha256"],
                             self.packet["artifacts"][key]["probe"]["video_sha256"])

    def test_rubric_discriminates_coherence_not_complexity(self):
        lh = self.reviews[0]["dimensions"]["d1_visual_story_relevance"]["verdict"]
        fi = self.reviews[1]["dimensions"]["d1_visual_story_relevance"]["verdict"]
        self.assertEqual(lh, "FAIL_CANDIDATE")
        self.assertEqual(fi, "PARTIAL")

    def test_consumer_decisions_are_source_bound(self):
        for decision, review in zip(self.decisions, self.reviews):
            self.assertEqual(decision["verdict"], "REVISE")
            self.assertTrue(decision["selection_changed"])
            self.assertTrue(decision["requires_controller_readback"])
            self.assertEqual(decision["media_sha256"], review["media_sha256"])
            self.assertIn("not authorize", decision["reason"].lower(),
                          "decision must state it grants no publishing authorization")


if __name__ == "__main__":
    unittest.main()
